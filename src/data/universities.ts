// Flat sorted string list of all approved universities
export const WORLDWIDE_UNIVERSITIES_NAMES: string[] = Array.from(
  new Set(WORLDWIDE_APPROVED_UNIVERSITIES.map((u) => u.name))
).sort((a, b) => a.localeCompare(b));

// Backward compatibility with legacy export
export const UNIVERSITIES_LIST = WORLDWIDE_UNIVERSITIES_NAMES;

export function getUniversityByName(name: string): ApprovedUniversity | undefined {
  return WORLDWIDE_APPROVED_UNIVERSITIES.find(
    (u) => u.name.toLowerCase() === name.toLowerCase() || u.shortName?.toLowerCase() === name.toLowerCase()
  );
}

export function searchWorldwideUniversities(query: string, region?: string): ApprovedUniversity[] {
  const cleanQ = query.trim().toLowerCase();
  return WORLDWIDE_APPROVED_UNIVERSITIES.filter((u) => {
    if (region && region !== 'All Regions' && u.region !== region) {
      return false;
    }
    if (!cleanQ) return true;
    return (
      u.name.toLowerCase().includes(cleanQ) ||
      (u.shortName && u.shortName.toLowerCase().includes(cleanQ)) ||
      u.country.toLowerCase().includes(cleanQ) ||
      u.domain.toLowerCase().includes(cleanQ)
    );
  });
}
